#!/usr/bin/env python3
"""Builds results/TABLES.md (every scenario x resolution x candidate with
p50/p95/p99/max) from the raw results/*.md. Usage: python3 -I gen_tables.py"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results")

CANDIDATES = [
    ("A  current Painter, full quality", "a-plain"),
    ("A' current Painter, moving level of detail", "a-motion"),
    ("B  plain cairo vector", "b-plain"),
    ("C  tiny-skia", "c-plain"),
    ("C' tiny-skia, cached layer + integer translate", "c-cached"),
    ("D  GL (SVGA3D hardware), draw, GPU completion forced", "d-hw-sync"),
    ("D  GL (SVGA3D hardware), draw + glReadPixels into cairo", "d-hw-readback"),
    ("D  GL (llvmpipe, forced software), draw", "d-sw"),
    ("D  GL (llvmpipe, forced software), draw + readback", "d-sw-readback"),
    ("D2 femtovg on GL (SVGA3D hardware), labels 300, GPU finish", "femtovg-hw"),
    ("E  wgpu offscreen, Vulkan = llvmpipe (lavapipe)", "wgpu"),
]
LABEL_CANDIDATES = [
    ("A  current Painter (its own label code)", "a-labels"),
    ("A' current Painter, moving level of detail", "a-motion"),
    ("B  plain cairo + cached bitmaps", "b-labels"),
    ("C  tiny-skia + cached pixmaps", "c-labels"),
    ("D  GL (SVGA3D) atlas labels, GPU completion forced", "d-hw-sync-labels"),
    ("D  GL (SVGA3D) atlas labels + readback", "d-hw-labels"),
    ("D  GL (llvmpipe) atlas labels + readback", "d-sw-labels"),
    ("D2 femtovg text engine (SVGA3D)", "femtovg-hw"),
]
STRESS = [
    ("A  current Painter", "{}-a"),
    ("B  plain cairo", "{}-b"),
    ("C  tiny-skia", "{}-c"),
    ("D  GL SVGA3D draw, GPU completion forced", "{}-dsync"),
    ("D  GL SVGA3D draw + readback", "{}-dhw"),
    ("D  GL llvmpipe draw + readback", "{}-dsw"),
]
STRESS_FILES = {
    "packed": {"a": "a-packed", "b": "b-packed", "c": "c-packed", "dhw": "d-hw-packed"},
    "dense": {"a": "a-dense", "b": "b-dense", "c": "c-dense", "dsync": "d-hw-sync-dense",
              "dhw": "d-hw-dense", "dsw": "d-sw-dense"},
}


def load(name):
    path = os.path.join(R, name + ".md")
    out = {}
    if not os.path.exists(path):
        return out
    for line in open(path):
        if not re.match(r"\| \d+x\d+@", line):
            continue
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        res = c[0].split(" ")[0]
        out[(res, c[1])] = (c[3], c[4], c[5], c[6], c[7])
    return out


def table(title, res, scen, cands):
    lines = [f"#### {title}: {res}, {scen}", "",
             "| candidate | cold frame | p50 | p95 | p99 | max |", "|---|---:|---:|---:|---:|---:|"]
    for label, name in cands:
        row = load(name).get((res, scen))
        if row:
            lines.append(f"| {label} | {row[0]} | {row[1]} | {row[2]} | {row[3]} | {row[4]} |")
        else:
            lines.append(f"| {label} | – | – | – | – | – |")
    return "\n".join(lines) + "\n"


RES = [f"{w}x{h}@{s}" for s in (1, 2) for (w, h) in ((1920, 1080), (2560, 1440), (3840, 2160))]
out = ["# Full tables (ms per frame; generated by gen_tables.py from results/*.md)\n",
       "Fixture `app` unless stated. Device pixels = logical x scale. `–` = not measured (reduced matrix or skipped).\n"]
out.append("## Geometry only (no labels)\n")
for scen in ("pan", "pan-fit", "zoom-out"):
    for res in RES:
        out.append(table("geometry", res, scen, CANDIDATES))
out.append("## 300 labels at 11-14 px\n")
for scen in ("pan", "pan-fit", "zoom-out"):
    for res in RES:
        out.append(table("labels", res, scen, LABEL_CANDIDATES))
for fixture, files in STRESS_FILES.items():
    out.append(f"## Fixture `{fixture}`\n")
    cands = [(lab, files[key.split("-")[-1]]) for lab, key in STRESS if key.split("-")[-1] in files]
    for scen in ("pan", "pan-fit", "zoom-out"):
        for res in ("1920x1080@1", "3840x2160@1", "3840x2160@2"):
            out.append(table(fixture, res, scen, cands))
open(os.path.join(R, "TABLES.md"), "w").write("\n".join(out))
print("wrote results/TABLES.md", sum(len(x) for x in out) // 1000, "kB")
